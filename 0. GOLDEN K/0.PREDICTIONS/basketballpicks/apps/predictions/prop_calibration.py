"""Per-(market, line, side) calibration of the player-prop probabilities
(bball-03 §6a) — the `totals_calibration.py` pattern, generalized to props.

rebounds-over-7.5 is a DIFFERENT calibration cell from rebounds-over-9.5, so we
fit a per-(market_key, line, side) isotonic calibrator on pre-cutoff walk-forward
history and apply it wherever a prop probability is SERVED. Only the §5
calibratable markets are fit (points / rebounds / assists / pra / pr / pa / ra);
the noise markets (blocks / steals / threes / first-basket) are NEVER fit here —
they are devig/display-only and must not carry a model-trusted calibrated edge.

Artifact-gated: with no artifact present every cell is the identity, so nothing
changes until a calibrator is fit (gitignored + regenerated by a
`calibrate_props` command). Fit on kickoff < cutoff keeps the dev window and the
sealed holdout out of sample (bball-03 §7c/§7d).
"""

import json
import os
from pathlib import Path

import numpy as np

from apps.predictions.calibration import IsotonicCalibrator

ARTIFACT = "artifacts/prop_calibrators.json"
MIN_FIT = 200  # per (market, line, side) minimum to fit at all
SIDES = ("OVER", "UNDER")

# bball-03 §5: only these markets may be calibrated into a trusted edge. Combos
# derive from these columns at settle time.
CALIBRATABLE_MARKETS = ("points", "rebounds", "assists", "pra", "pr", "pa", "ra")

# market_key -> the PlayerBoxScore-derived realized value (settlement math; the
# authoritative settle_expr lives in apps.props, this local map covers only the
# calibratable stats we fit here).
_SETTLE = {
    "points": lambda b: b["pts"],
    "rebounds": lambda b: b["reb"],
    "assists": lambda b: b["ast"],
    "pra": lambda b: b["pts"] + b["reb"] + b["ast"],
    "pr": lambda b: b["pts"] + b["reb"],
    "pa": lambda b: b["pts"] + b["ast"],
    "ra": lambda b: b["reb"] + b["ast"],
}

_CACHE: dict[tuple, dict] = {}


def _key(market_key: str, line: float, side: str) -> str:
    return f"{market_key}:{float(line):g}:{side}"


def _artifact_path() -> Path:
    from django.conf import settings

    return Path(settings.BASE_DIR) / ARTIFACT


def _load() -> dict:
    path = _artifact_path()
    try:
        mtime = os.path.getmtime(path)
    except OSError:
        mtime = None
    key = (str(path), mtime)
    if key not in _CACHE:
        if mtime is None:
            _CACHE[key] = {}
        else:
            data = json.loads(path.read_text(encoding="utf-8"))
            _CACHE[key] = {
                k: IsotonicCalibrator.from_dict(v)
                for k, v in (data.get("calibrators") or {}).items()
            }
    return _CACHE[key]


def clear_cache() -> None:
    _CACHE.clear()


def calibrate(market_key: str, line: float, side: str, p: float) -> float:
    """Honest served probability for a prop (market, line, side). Identity when
    no calibrator is fit for that cell (or no artifact at all)."""
    cal = _load().get(_key(market_key, line, side))
    if cal is None:
        return float(p)
    return float(np.clip(cal.predict([float(p)])[0], 0.0, 1.0))


def fit_from_predictions(cutoff, lines_per_market: dict[str, list[float]]):
    """Fit per-(market, line, side) isotonic on PropPrediction rows whose game
    tipped before `cutoff`, pricing each requested line off the stored pmf and
    grading against the realized PlayerBoxScore stat.

    `lines_per_market`: {market_key: [7.5, 9.5, ...]} — the lines to calibrate
    (typically the common book lines). Returns ({cell: IsotonicCalibrator},
    {cell: n})."""
    from apps.core.models import PlayerBoxScore
    from apps.predictions.engines.prop_stats import StatDistribution
    from apps.predictions.models import PropPrediction

    claims: dict[str, tuple[list, list]] = {}
    box_by_game_player: dict = {}
    for b in PlayerBoxScore.objects.values("game_id", "player_id", "pts", "reb", "ast").iterator(
        chunk_size=5000
    ):
        box_by_game_player[(b["game_id"], b["player_id"])] = b

    qs = PropPrediction.objects.filter(
        market_key__in=[m for m in lines_per_market if m in CALIBRATABLE_MARKETS],
        game__tipoff_utc__lt=cutoff,
    ).values("game_id", "player_id", "market_key", "pmf", "support_start")
    for r in qs.iterator(chunk_size=5000):
        box = box_by_game_player.get((r["game_id"], r["player_id"]))
        if box is None or not r["pmf"]:
            continue
        actual = _SETTLE[r["market_key"]](box)
        dist = StatDistribution(r["pmf"], r["support_start"])
        for line in lines_per_market[r["market_key"]]:
            over_p = dist.prob_over(line)
            ck_o, ck_u = _key(r["market_key"], line, "OVER"), _key(r["market_key"], line, "UNDER")
            claims.setdefault(ck_o, ([], []))
            claims.setdefault(ck_u, ([], []))
            claims[ck_o][0].append(over_p)
            claims[ck_o][1].append(1.0 if actual > line else 0.0)
            claims[ck_u][0].append(1.0 - over_p)
            claims[ck_u][1].append(1.0 if actual < line else 0.0)

    cals, counts = {}, {}
    for cell, (xs, ys) in claims.items():
        counts[cell] = len(xs)
        if len(xs) >= MIN_FIT:
            cals[cell] = IsotonicCalibrator().fit(np.asarray(xs), np.asarray(ys))
    return cals, counts


def save(cals: dict, cutoff_iso: str, counts: dict) -> Path:
    path = _artifact_path()
    path.parent.mkdir(parents=True, exist_ok=True)
    payload = {
        "cutoff": cutoff_iso,
        "counts": counts,
        "calibrators": {k: c.to_dict() for k, c in cals.items()},
    }
    path.write_text(json.dumps(payload, indent=1), encoding="utf-8")
    clear_cache()
    return path
